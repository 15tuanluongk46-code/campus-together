import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const endpoint = process.argv[2];
if (!endpoint) throw new Error('Provide the test-owned extracted runtime endpoint');
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}), args: ['--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1100, height: 720 } });
const evidence = process.env.CAMPUS_EVIDENCE_DIR;
if (evidence) await mkdir(evidence, { recursive: true });
const errors = []; page.on('pageerror', error => errors.push(error.message)); page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
try {
  await page.goto(endpoint); await page.waitForLoadState('networkidle');
  if (evidence) await page.screenshot({ path: resolve(evidence, 'archive-title.png') });
  await page.getByLabel('Bạn tên là gì?').fill('Solo archive');
  await page.getByRole('button', { name: 'Chơi một mình', exact: true }).click({ timeout: 60000 });
  await page.getByRole('button', { name: 'Vào sân · Bật điều khiển chuột' }).waitFor({ timeout: 30000 });
  if (!(await page.locator('.play-dialog').innerText()).includes('18 phút')) throw new Error('Archive client is not Solo-aware');
  if (evidence) await page.screenshot({ path: resolve(evidence, 'archive-solo.png') });
  await page.getByRole('button', { name: 'Vào sân · Bật điều khiển chuột' }).click();
  await page.waitForFunction(() => !!document.pointerLockElement);
  await page.keyboard.press('KeyS', { delay: 300 });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Rời phòng', exact: true }).click();
  await page.getByRole('button', { name: 'Ở lại', exact: true }).click();
  await page.getByRole('button', { name: 'Tiếp tục · Bật điều khiển chuột' }).waitFor();
  await page.getByRole('button', { name: 'Rời phòng', exact: true }).click();
  await page.getByRole('button', { name: 'Rời lượt chơi', exact: true }).click();
  await page.getByRole('button', { name: 'Chơi một mình', exact: true }).waitFor();
  await page.getByRole('button', { name: /Tạo phòng cùng bạn/ }).click();
  await page.getByRole('heading', { name: 'Nhóm của chúng mình' }).waitFor();
  const code = await page.locator('#invite-code').innerText();
  const partner = await browser.newPage({ viewport: { width: 1100, height: 720 } });
  partner.on('pageerror', error => errors.push(error.message));
  partner.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  await partner.goto(`${endpoint}/?room=${code}`); await partner.waitForLoadState('networkidle');
  await partner.getByLabel('Bạn tên là gì?').fill('Bạn archive');
  await partner.getByRole('button', { name: 'Tham gia phòng', exact: true }).click({ timeout: 60000 });
  await partner.getByRole('heading', { name: 'Nhóm của chúng mình' }).waitFor();
  await page.getByRole('button', { name: 'Mình sẵn sàng' }).click();
  await partner.getByRole('button', { name: 'Mình sẵn sàng' }).click();
  await page.locator('[data-action="start"]').click();
  await page.getByRole('button', { name: 'Vào sân · Bật điều khiển chuột' }).waitFor();
  await partner.getByRole('button', { name: 'Vào sân · Bật điều khiển chuột' }).waitFor();
  if (evidence) await page.screenshot({ path: resolve(evidence, 'archive-coop.png') });
  await partner.close();
  if (errors.length) throw new Error(JSON.stringify(errors));
  console.log(JSON.stringify({ soloTitle: true, realMatchmaking: true, onboarding18min: true, pointerLock: true, leaveCancel: true, leaveConfirmed: true, coopTwoBrowserContexts: true, coopReadyStart: true, errors }));
} finally { await browser.close(); }
